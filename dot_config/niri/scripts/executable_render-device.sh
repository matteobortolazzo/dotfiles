#!/usr/bin/env bash
# Pick niri's render GPU for this session, before niri starts (ExecStartPre
# drop-in on niri.service). On the hybrid laptop each display is wired to one
# GPU: eDP to the Intel iGPU, the external DP port to the NVIDIA dGPU. Rendering
# on a GPU that does not drive the screen means a cross-GPU copy every frame,
# which lags in both directions (niri-wm/niri#3095, #4708). So:
#   - something connected to the NVIDIA card -> render on NVIDIA
#   - otherwise (laptop panel only)          -> render on the iGPU
# niri reads render-drm-device only at startup; replugging needs a re-login.
# Writes ~/.config/niri/render.kdl, included by host.kdl.
set -euo pipefail

out="${XDG_CONFIG_HOME:-$HOME/.config}/niri/render.kdl"

render_node() { # $1 = /sys/class/drm/cardN
    local n
    for n in "$1"/device/drm/renderD*; do
        [[ -e $n ]] && { echo "/dev/dri/${n##*/}"; return; }
    done
}

has_connected() { # $1 = /sys/class/drm/cardN
    local s
    for s in "$1"-*/status; do
        [[ -r $s && $(<"$s") == connected ]] && return 0
    done
    return 1
}

nvidia='' igpu=''
for card in /sys/class/drm/card*; do
    [[ ${card##*/} == *-* ]] && continue   # connector, not a card
    case $(<"$card/device/vendor") in
        0x10de) nvidia=$card ;;
        *) [[ -z $igpu ]] && igpu=$card ;;
    esac
done

if [[ -n $nvidia ]] && has_connected "$nvidia"; then
    node=$(render_node "$nvidia")
    reason="display on the NVIDIA dGPU"
    extra=$'\n    emulate-zero-presentation-time'
elif [[ -n $igpu ]]; then
    node=$(render_node "$igpu")
    reason="laptop panel only, on the iGPU"
    extra=''
else
    node=''
fi

if [[ -n $node ]]; then
    body="// Generated by ~/.config/niri/scripts/render-device.sh at niri start: ${reason}.
debug {
    render-drm-device \"${node}\"${extra}
}"
else
    body="// Generated by ~/.config/niri/scripts/render-device.sh: no GPU found, niri default."
fi

# Only touch the file when the choice changes.
if [[ ! -f $out || $(<"$out") != "$body" ]]; then
    printf '%s\n' "$body" >"$out.tmp"
    mv "$out.tmp" "$out"
fi
echo "render-device: ${node:-default} (${reason:-none})"
